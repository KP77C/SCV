#!/usr/bin/env python3
# mkfont.py - renders the controls-menu font (Inter Medium, SIL Open Font
# License 1.1) into an 8-bit coverage atlas: src/sc_font.h.
#   python3 tools/mkfont.py /usr/share/fonts/opentype/inter/Inter-Medium.otf 20 > src/sc_font.h
import sys
from PIL import Image, ImageDraw, ImageFont
path, size = sys.argv[1], int(sys.argv[2])
f = ImageFont.truetype(path, size)
asc, desc = f.getmetrics()
h = asc + desc
glyphs, cols = [], []
x = 0
for c in range(32, 127):
    ch = chr(c)
    adv = int(round(f.getlength(ch)))
    l, t, r, b = f.getbbox(ch)
    l = min(l, 0); r = max(r, adv)
    w = max(r - l, 1)
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-l, 0), ch, font=f, fill=255)
    glyphs.append((x, w, l, adv)); cols.append(im); x += w
atlas = Image.new("L", (x, h), 0)
for (gx, w, l, adv), im in zip(glyphs, cols): atlas.paste(im, (gx, 0))
print("// sc_font.h - generated by tools/mkfont.py from %s at %dpx." % (path.split('/')[-1], size))
print("// Inter is (c) The Inter Project Authors, SIL Open Font License 1.1 (see third_party/Inter-OFL.txt).")
print("#pragma once\n#include <cstdint>\nnamespace sc { namespace font {")
print("constexpr int kH = %d, kAscent = %d, kAtlasW = %d;" % (h, asc, x))
print("struct Glyph { uint16_t x; uint8_t w; int8_t left; uint8_t adv; };")
print("constexpr Glyph kGlyphs[95] = {")
print(",".join("{%d,%d,%d,%d}" % g for g in glyphs))
print("};")
print("constexpr uint8_t kAtlas[%d] = {" % (x * h))
data = atlas.tobytes()
for i in range(0, len(data), 40): print(",".join(str(v) for v in data[i:i+40]) + ",")
print("};\n} }  // namespace sc::font")
