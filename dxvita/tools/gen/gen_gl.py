#!/usr/bin/env python3
"""Generate dx_gl_gen.inc: one OPENGL32.dll shim per GL entry point the game's
OpenGlDrv.dll asks for (tools/gen/opengldrv_names.txt).

Each shim reads the stdcall arguments off the guest stack (doubles take two
dwords), turns guest pointers into host pointers (the guest arena is one
block, so that is just an offset) and calls the real GL: Mesa's OSMesa on the
qemu host, vitaGL on the Vita.

usage: gen_gl.py names.txt gl.h [glext.h ...] [--have syms.txt] > dx_gl_gen.inc
  --have: entry points the target GL library really has (nm output names);
          the others become logged stubs.
"""
import re, sys

args = sys.argv[1:]
have = None
if '--have' in args:
    i = args.index('--have'); have = set(open(args[i + 1]).read().split()); del args[i:i + 2]
names = [l.strip() for l in open(args[0]) if l.strip()]
protos = {}
pat = re.compile(r'GLAPI\s+([\w \t\*]+?)\s*(?:GLAPIENTRY|APIENTRY)\s+(gl\w+)\s*\(([^)]*)\)\s*;', re.S)
for h in args[1:]:
    txt = open(h).read()
    for ret, name, params in pat.findall(txt):
        protos.setdefault(name, (' '.join(ret.split()), ' '.join(params.split())))

INT = {'GLenum', 'GLboolean', 'GLbitfield', 'GLbyte', 'GLshort', 'GLint', 'GLsizei', 'GLubyte',
       'GLushort', 'GLuint', 'GLhandleARB', 'GLchar', 'GLintptr', 'GLsizeiptr'}
FLT = {'GLfloat', 'GLclampf'}
DBL = {'GLdouble', 'GLclampd'}

out = ['// Generated by tools/gen/gen_gl.py — do not edit.']
words = {}
for n in names:
    if not n.startswith('gl'):
        continue
    if n not in protos:
        out.append(f'// {n}: no prototype found')
        continue
    ret, params = protos[n]
    plist = [] if params.strip() in ('', 'void') else [p.strip() for p in params.split(',')]
    call, w = [], 0
    for p in plist:
        p = p.replace('const ', '').strip()
        ptr = '*' in p
        typ = p.split('*')[0].split()[0] if ptr else p.split()[0]
        if ptr:
            call.append(f'({typ}{"*" * p.count("*")})GP(c, A[{w}])'); w += 1
        elif typ in DBL:
            call.append(f'GD(A, {w})'); w += 2
        elif typ in FLT:
            call.append(f'GF(A, {w})'); w += 1
        elif typ in INT:
            call.append(f'({typ})A[{w}]'); w += 1
        else:
            raise SystemExit(f'{n}: unknown type {p!r}')
    words[n] = w
    # Host pointers can't go back to the guest: those few are hand-written.
    if n in ('glGetPointerv',):
        out.append(f'// {n}: returns host pointers, written by hand'); continue
    available = have is None or n in have
    target = n
    if not available:
        # ARB/EXT names folded into core GL, under the core name.
        for suf in ('ARB', 'EXT'):
            if n.endswith(suf) and have is not None and n[:-len(suf)] in have:
                target, available = n[:-len(suf)], True
    if not available and n in ('glLockArraysEXT', 'glUnlockArraysEXT'):
        # Compiled vertex arrays are only a hint.
        out.append(f'G("{n}", {w}, [](Cpu&, const uint32_t*) -> uint32_t {{ return 0; }});'); continue
    if not available:
        out.append(f'G("{n}", {w}, [](Cpu&, const uint32_t*) -> uint32_t {{ gl_missing("{n}"); return 0; }});')
        continue
    body = f'{target}({", ".join(call)})'
    if ret == 'void':
        out.append(f'G("{n}", {w}, [](Cpu& c, const uint32_t* A) -> uint32_t {{ (void)c; (void)A; GLCOUNT("{n}"); {body}; return 0; }});')
    elif '*' in ret:
        out.append(f'// {n}: pointer return, written by hand')
    else:
        out.append(f'G("{n}", {w}, [](Cpu& c, const uint32_t* A) -> uint32_t {{ (void)c; (void)A; GLCOUNT("{n}"); return (uint32_t){body}; }});')
print('\n'.join(out))
